-- Transactional outbox. An event is inserted here in the same transaction that changes the order,
-- so the two succeed or fail together. A relay (OutboxRelay) sends unpublished rows to Kafka in id
-- order and sets published_at; published rows are purged after shopflow.outbox-retention.
create table outbox_events (
    id          bigint generated by default as identity primary key,
    event_id    varchar(64)   not null unique,
    message_key varchar(64)   not null,
    -- The envelope as JSON. Events are small; the writer rejects anything longer.
    payload     varchar(4000) not null,
    created_at  timestamp(6) with time zone not null,
    published_at timestamp(6) with time zone
);

-- The relay reads the oldest unpublished rows.
create index idx_outbox_events_published_at_id on outbox_events (published_at, id);
