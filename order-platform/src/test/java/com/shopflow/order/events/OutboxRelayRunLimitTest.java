package com.shopflow.order.events;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatCode;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.time.ZoneId;
import java.time.ZoneOffset;
import java.util.concurrent.CompletableFuture;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.kafka.core.KafkaTemplate;
import org.springframework.kafka.support.SendResult;

import com.shopflow.order.ShopFlowProperties;

import io.micrometer.core.instrument.simple.SimpleMeterRegistry;

/**
 * The relay holds a ShedLock lease of 2 minutes. A run that goes on longer lets a second instance start
 * and send the same rows, which can reorder events. A run must therefore stop starting sends once it has
 * been going for {@link OutboxRelay#MAX_RUN}. The clock here is moved by the (fake) broker, so the test
 * does not depend on real time.
 */
class OutboxRelayRunLimitTest {

	/** How long each send takes: slow, but still inside the 5 s send timeout. */
	private static final Duration SEND_TIME = Duration.ofSeconds(20);

	private EmbeddedDatabase database;

	private JdbcClient jdbc;

	private MovableClock clock;

	private KafkaTemplate<String, String> kafka;

	private OutboxRelay relay;

	private final SimpleMeterRegistry meters = new SimpleMeterRegistry();

	@BeforeEach
	@SuppressWarnings("unchecked")
	void setUp() {
		this.database = new EmbeddedDatabaseBuilder().generateUniqueName(true).setType(EmbeddedDatabaseType.H2).build();
		this.jdbc = JdbcClient.create(this.database);
		this.jdbc.sql("""
				create table outbox_events (
				    id bigint generated by default as identity primary key,
				    event_id varchar(64) not null unique,
				    message_key varchar(64) not null,
				    payload varchar(4000) not null,
				    created_at timestamp(6) with time zone not null,
				    published_at timestamp(6) with time zone
				)
				""").update();
		for (int i = 1; i <= 10; i++) {
			this.jdbc.sql("insert into outbox_events (event_id, message_key, payload, created_at) "
					+ "values (:event, 'k', '{}', current_timestamp)").param("event", "evt-" + i).update();
		}
		this.clock = new MovableClock(Instant.parse("2026-01-01T00:00:00Z"));
		this.kafka = mock(KafkaTemplate.class);
		when(this.kafka.send(anyString(), anyString(), anyString())).thenAnswer(call -> {
			this.clock.advance(SEND_TIME);
			return CompletableFuture.completedFuture(mock(SendResult.class));
		});
		this.relay = new OutboxRelay(this.jdbc, this.kafka, mock(ShopFlowProperties.class), this.clock,
				this.meters);
	}

	@AfterEach
	void tearDown() {
		this.database.shutdown();
	}

	@Test
	void aRunStopsStartingSendsAfterTheMaximumRunTime() {
		this.relay.publishPending();

		// 3 sends take 60 s; the fourth must not start.
		verify(this.kafka, Mockito.times(3)).send(anyString(), anyString(), any());
		assertThat(published()).isEqualTo(3);
	}

	@Test
	void theNextRunContinuesInOrderWhereTheLastOneStopped() {
		this.relay.publishPending();
		this.relay.publishPending();

		assertThat(published()).isEqualTo(6);
		assertThat(this.jdbc.sql("select max(id) from outbox_events where published_at is not null")
				.query(Long.class).single()).isEqualTo(6L);
	}

	@Test
	void aRejectedRowStopsTheRunAndIsCounted() {
		when(this.kafka.send(anyString(), anyString(), anyString()))
				.thenReturn(CompletableFuture.failedFuture(new IllegalStateException("record too large")));

		this.relay.publishPending();

		assertThat(published()).isZero();
		assertThat(this.meters.counter(OutboxRelay.FAILURES).count()).isEqualTo(1.0);
		verify(this.kafka, Mockito.times(1)).send(anyString(), anyString(), any());
	}

	@Test
	void aFailureToMarkARowPublishedDoesNotEscapeTheRunAndTheRowIsLeftForTheNextRun() {
		this.jdbc.sql("alter table outbox_events add constraint ck_never_marked check (published_at is null)").update();

		assertThatCode(this.relay::publishPending).doesNotThrowAnyException();

		assertThat(published()).isZero();
		verify(this.kafka, Mockito.times(1)).send(anyString(), anyString(), any());
	}

	private long published() {
		return this.jdbc.sql("select count(*) from outbox_events where published_at is not null")
				.query(Long.class).single();
	}

	private static final class MovableClock extends Clock {

		private Instant now;

		MovableClock(Instant start) {
			this.now = start;
		}

		void advance(Duration by) {
			this.now = this.now.plus(by);
		}

		@Override
		public ZoneId getZone() {
			return ZoneOffset.UTC;
		}

		@Override
		public Clock withZone(ZoneId zone) {
			return this;
		}

		@Override
		public Instant instant() {
			return this.now;
		}
	}
}
