-- Events the consumer could not handle after all retries (see DeadLetters). The same record also
-- stays in the order-events-dlt topic; this table makes it searchable and gives operators a worklist.
-- (original_topic, original_partition, original_offset) identify the message on the main topic and
-- stay the same through all retry hops, so a dead letter delivered twice is stored once.
create table dead_letters (
    id                 bigint generated by default as identity primary key,
    original_topic     varchar(255)  not null,
    original_partition integer       not null,
    original_offset    bigint        not null,
    message_key        varchar(64),
    event_id           varchar(64),
    event_type         varchar(64),
    -- The envelope as JSON, cut to this length if it is longer.
    payload            varchar(4000) not null,
    exception_class    varchar(255),
    error_message      varchar(2000),
    dead_lettered_at   timestamp(6) with time zone not null,
    constraint uq_dead_letters_origin unique (original_topic, original_partition, original_offset)
);

create index idx_dead_letters_dead_lettered_at on dead_letters (dead_lettered_at);
